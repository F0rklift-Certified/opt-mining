"""
Shared helpers for Task 4 geographic & environmental data retrieval.

The vector sources (ABS ASGS boundaries, DCCEEW CAPAD protected areas) are
ArcGIS REST FeatureServer layers that serve GeoJSON directly (``f=geojson``),
so no geospatial vector library is needed: features arrive as GeoJSON dicts
and are handled with the standard library. Rasters (SRTM elevation, ABARES
NLUM land use) are read with rasterio, windowed over /vsicurl// vsizip so the
national files are never downloaded in full (Constitution: do not download or
process more data than the analysis requires).

Endpoints:
  ABS ASGS 2021  https://geo.abs.gov.au/arcgis/rest/services/ASGS2021
  CAPAD 2024     https://gis.environment.gov.au/gispubmap/rest/services/ogc_services/CAPAD/FeatureServer
  ABARES NLUM    https://www.agriculture.gov.au/abares/aclump (zip downloads)
  SRTM GL1/GL3   https://opentopography.s3.sdsc.edu/raster/ (public S3 mirror)

Licence: see DATA/geographic/DATA_PROVENANCE.md
"""

