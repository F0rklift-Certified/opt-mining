"""
Infrastructure inspect stage — examine substations, power lines, generators.

Reads the pre-downloaded GA Electricity Infrastructure GeoJSON files,
filters by state/fuel, writes filtered subsets, and produces inspection
reports with statistics and an SVG preview for power lines.

Importable entry point:
    from pipeline.infrastructure.inspect import run
    result = run(verbose=False, state="NSW", fuel_type="wind")

Output:
    DATA/infrastructure/metadata/ga_substations_2026_inspection.md
    DATA/infrastructure/metadata/ga_power_lines_2026_inspection.md
    DATA/infrastructure/metadata/ga_power_lines_2026_preview.svg
    DATA/infrastructure/metadata/ga_generators_2026_inspection.md
"""

from __future__ import annotations

from pathlib import Path

from . import config
from .helpers import (
    compute_bounds,
    compute_field_stats,
    count_geometry_types,
    count_property,
    count_valid_coordinates,
    filter_by_fuel_type,
    filter_by_state,
    load_geojson,
    write_geojson,
)
from ..common.geo import utc_now


# ---------------------------------------------------------------------------
