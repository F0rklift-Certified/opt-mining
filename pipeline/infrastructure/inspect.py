def _inspect_generators(state: str, fuel_type: str, verbose: bool = False) -> Path:
    """Inspect GA generators and create fuel-type + state subsets."""
    source_path = config.INFRA_DIR / "generators" / "ga_powerstations_2026_australia.geojson"
    collection = load_geojson(source_path)
    features = collection["features"]

    fuel_features = filter_by_fuel_type(features, fuel_type)
    state_features = filter_by_state(fuel_features, state)

    fuel_label = fuel_type.lower().replace(" ", "_")
    state_label = state.lower() if state.upper() != "ALL" else "all"
    output_dir = config.INFRA_DIR / "generators"

    # Write filtered outputs
    for out_path, name, selected in [
        (output_dir / f"ga_{fuel_label}_generators_2026_australia.geojson",
         f"GA {fuel_type.title()} Generators 2026", fuel_features),
        (output_dir / f"ga_{fuel_label}_generators_2026_{state_label}.geojson",
         f"GA {fuel_type.title()} Generators 2026 — {state.upper()}", state_features),
    ]:
        derived = {**collection, "name": name, "features": selected}
        write_geojson(out_path, derived)

    # Stats
    field_info = compute_field_stats(features)
    technologies = count_property(features, "technology_type")
    fuels = count_property(features, "primary_fuel_type")
    statuses = count_property(features, "status")
    fuel_states = count_property(fuel_features, "state")
    valid_coords = count_valid_coordinates(features)

    report = f"""# Geoscience Australia Generators 2026 — Inspection

*Generated by `pipeline.infrastructure.inspect` on {utc_now()}. Do not edit by hand.*

- Source: `https://services.ga.gov.au/gis/rest/services/Electricity_Infrastructure/MapServer/1`
- Custodian: Geoscience Australia
- Attribution: (c) Commonwealth of Australia (Geoscience Australia) 2026
- Format: ArcGIS Feature Service downloaded as GeoJSON
- CRS: EPSG:7844 (GDA2020)
- National feature count: {len(features)}
- Fuel type filter: {fuel_type}
- Filtered feature count (national): {len(fuel_features)}
- State filter: {state.upper()}
- Filtered feature count (state): {len(state_features)}
- Valid point coordinates: {valid_coords}/{len(features)}
- Technology values: {technologies}
- Fuel values: {fuels}
- Generator status values: {statuses}
- {fuel_type.title()} features by state: {fuel_states}
- Missing values by field: {field_info['missing']}

## Initial assessment

The layer provides a useful public reference set for existing generation
facilities and can identify {fuel_type} facilities for later validation. It includes
technology/fuel type, capacity, status and point coordinates.
"""
    report_path = config.INFRA_META_DIR / "ga_generators_2026_inspection.md"
    report_path.write_text(report, encoding="utf-8")
    if verbose:
        print(f"      Generators: {len(fuel_features)} {fuel_type}, "
              f"{len(state_features)} in {state.upper()}")
    return report_path


# ---------------------------------------------------------------------------
# Public entry point
# ---------------------------------------------------------------------------


def run(
    verbose: bool = False,
    state: str = config.DEFAULT_STATE,
    fuel_type: str = config.DEFAULT_FUEL_TYPE,
) -> dict:
    """
    Inspect all infrastructure datasets.

    Returns a summary dict with output paths.
    """
    outputs: list[Path] = []

    print("  Inspecting substations...")
    outputs.append(_inspect_substations(state, verbose))

    print("  Inspecting power lines...")
    report, svg = _inspect_power_lines(state, verbose)
    outputs.extend([report, svg])

    print("  Inspecting generators...")
    outputs.append(_inspect_generators(state, fuel_type, verbose))

    print(f"    {len(outputs)} output(s)")
    return {"reports": outputs}
