# ---------------------------------------------------------------------------


def _inspect_substations(state: str, verbose: bool = False) -> Path:
    """Inspect GA substations and create state subset."""
    source_path = config.INFRA_DIR / "substations" / "ga_substations_2026_australia.geojson"
    collection = load_geojson(source_path)
    features = collection["features"]

    state_features = filter_by_state(features, state)
    state_label = state.lower() if state.upper() != "ALL" else "all"

    # Write filtered subset
    output_dir = config.INFRA_DIR / "substations"
    state_path = output_dir / f"ga_substations_2026_{state_label}.geojson"
    state_collection = {
        **collection,
        "name": f"Geoscience Australia Substations 2026 — {state.upper()}",
        "features": state_features,
    }
    write_geojson(state_path, state_collection)

    # Stats
    field_info = compute_field_stats(features)
    geometry_types = count_geometry_types(features)
    states = count_property(features, "state")
    statuses = count_property(features, "status")
    voltages = count_property(features, "voltage_kv")
    valid_coords = count_valid_coordinates(features)

    report = f"""# Geoscience Australia Substations 2026 — Inspection

*Generated by `pipeline.infrastructure.inspect` on {utc_now()}. Do not edit by hand.*

- Source: `https://services.ga.gov.au/gis/rest/services/Electricity_Infrastructure/MapServer/0`
- Custodian: Geoscience Australia
- Attribution: (c) Commonwealth of Australia (Geoscience Australia) 2026
- Format: ArcGIS Feature Service downloaded as GeoJSON
- CRS: EPSG:7844 (GDA2020)
- National feature count: {len(features)}
- State filter: {state.upper()}
- Filtered feature count: {len(state_features)}
- Geometry types: {dict(geometry_types)}
- Valid point coordinates: {valid_coords}/{len(features)}
- States: {states}
- Operational status values: {statuses}
- Voltage kV values: {dict(sorted(voltages.items()))}
- Missing values by field: {field_info['missing']}

## Fields

{', '.join(field_info['fields'])}

## Initial assessment

This dataset is suitable for screening-level proximity to transmission
substations. It provides point coordinates, voltage, state, locality, status and
spatial-confidence fields. It is not a complete engineering connection-capacity
register: a substation's voltage does not equal spare connection capacity.
"""
    report_path = config.INFRA_META_DIR / "ga_substations_2026_inspection.md"
    config.INFRA_META_DIR.mkdir(parents=True, exist_ok=True)
    report_path.write_text(report, encoding="utf-8")
    if verbose:
        print(f"      Substations: {len(state_features)} filtered ({state.upper()})")
    return report_path


