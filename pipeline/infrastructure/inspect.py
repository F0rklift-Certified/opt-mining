def _generate_power_lines_svg(
    features: list[dict], bounds: list[float], out_path: Path,
    width: int = 1000, height: int = 760, margin: int = 35,
    stroke_thin: float = 0.55, stroke_thick: float = 0.9,
    voltage_threshold: int = 220,
) -> None:
    """Generate an SVG preview map of power lines coloured by voltage."""
    min_x, min_y, max_x, max_y = bounds
    scale = min(
        (width - 2 * margin) / (max_x - min_x),
        (height - 2 * margin) / (max_y - min_y),
    )
    voltage_colours = {
        500: "#7f0000", 400: "#b30000", 330: "#d7301f", 275: "#ef6548",
        220: "#fc8d59", 132: "#3182bd", 110: "#6baed6", 88: "#9ecae1", 66: "#c6dbef",
    }

    def project(x, y):
        px = margin + (x - min_x) * scale
        py = height - margin - (y - min_y) * scale
        return px, py

    paths = []
    for feature in sorted(features, key=lambda f: int(f["properties"].get("capacity_kv") or 0)):
        voltage = int(feature["properties"].get("capacity_kv") or 0)
        colour = voltage_colours.get(voltage, "#999999")
        coords = feature["geometry"]["coordinates"]
        points = [project(x, y) for x, y in coords]
        path_data = " ".join(
            ("M" if i == 0 else "L") + f"{x:.2f},{y:.2f}"
            for i, (x, y) in enumerate(points)
        )
        sw = stroke_thin if voltage < voltage_threshold else stroke_thick
        paths.append(
            f'<path d="{path_data}" fill="none" stroke="{colour}" '
            f'stroke-width="{sw}" stroke-linecap="round"/>'
        )

    legend_items = []
    for i, voltage in enumerate(sorted(voltage_colours, reverse=True)):
        y = 80 + i * 24
        legend_items.append(
            f'<line x1="790" y1="{y}" x2="825" y2="{y}" '
            f'stroke="{voltage_colours[voltage]}" stroke-width="3"/>'
            f'<text x="835" y="{y + 5}" font-size="15">{voltage} kV</text>'
        )

    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">
<rect width="100%" height="100%" fill="white"/>
<text x="35" y="30" font-family="sans-serif" font-size="22" font-weight="bold">Geoscience Australia Power Lines 2026</text>
<text x="35" y="53" font-family="sans-serif" font-size="14">{len(features)} national features; colour represents nominal voltage</text>
<g>{''.join(paths)}</g>
<rect x="770" y="55" width="180" height="250" rx="6" fill="white" fill-opacity="0.9" stroke="#cccccc"/>
<g font-family="sans-serif">{''.join(legend_items)}</g>
</svg>"""
    out_path.write_text(svg, encoding="utf-8")


def _inspect_power_lines(state: str, verbose: bool = False) -> tuple[Path, Path]:
    """Inspect GA power lines: merge parts, filter, report + SVG preview."""
    parts = [
        config.INFRA_DIR / "transmission-lines" / "ga_power_lines_2026_part_001.geojson",
        config.INFRA_DIR / "transmission-lines" / "ga_power_lines_2026_part_002.geojson",
    ]
    collections = [load_geojson(p) for p in parts]
    features = [f for c in collections for f in c["features"]]
    object_ids = [f["properties"].get("objectid") for f in features]
    if len(object_ids) != len(set(object_ids)):
        raise RuntimeError("Duplicate OBJECTID values found across downloaded pages")

    output_dir = config.INFRA_DIR / "transmission-lines"
    output_dir.mkdir(parents=True, exist_ok=True)

    # Write merged national file
    merged = {
        "type": "FeatureCollection",
        "name": "Geoscience Australia Power Lines 2026",
        "crs": collections[0].get("crs"),
        "features": features,
    }
    merged_path = output_dir / "ga_power_lines_2026_australia.geojson"
    write_geojson(merged_path, merged)

    # State filter
    state_features = filter_by_state(features, state)
    state_label = state.lower() if state.upper() != "ALL" else "all"
    state_path = output_dir / f"ga_power_lines_2026_{state_label}.geojson"
    state_collection = {
        **merged,
        "name": f"Geoscience Australia Power Lines 2026 — {state.upper()}",
        "features": state_features,
    }
    write_geojson(state_path, state_collection)

    # Stats
    field_info = compute_field_stats(features)
    geometry_counts = count_geometry_types(features)
    states = count_property(features, "state")
    statuses = count_property(features, "status")
    capacities = count_property(features, "capacity_kv")
    bounds = compute_bounds(features)

    report = f"""# Geoscience Australia Power Lines 2026 — Inspection

*Generated by `pipeline.infrastructure.inspect` on {utc_now()}. Do not edit by hand.*

- Source: `https://services.ga.gov.au/gis/rest/services/Electricity_Infrastructure/MapServer/2`
- Custodian: Geoscience Australia
- Attribution: (c) Commonwealth of Australia (Geoscience Australia) 2026
- Format: ArcGIS Feature Service downloaded as GeoJSON
- CRS: EPSG:7844 (GDA2020)
- National feature count: {len(features)}
- State filter applied: {state.upper()}
- Filtered feature count: {len(state_features)}
- Duplicate OBJECTIDs: {len(object_ids) - len(set(object_ids))}
- Geometry types: {dict(geometry_counts)}
- Bounds: {[round(v, 6) for v in bounds] if bounds else 'N/A'}
- States: {states}
- Operational status values: {statuses}
- Capacity kV values: {dict(sorted(capacities.items()))}
- Missing values by field: {field_info['missing']}

## Fields

{', '.join(field_info['fields'])}

## Initial assessment

This national line dataset is suitable for screening-level straight-line
distance-to-transmission calculations and contains voltage, operational status,
state, revision and spatial-confidence attributes. It must not be treated as an
engineering asset register or used instead of asset-safety services.
"""
    report_path = config.INFRA_META_DIR / "ga_power_lines_2026_inspection.md"
    report_path.write_text(report, encoding="utf-8")

    # SVG preview
    preview_path = config.INFRA_META_DIR / "ga_power_lines_2026_preview.svg"
    if bounds:
        _generate_power_lines_svg(features, bounds, preview_path)

    if verbose:
        print(f"      Power lines: {len(features)} merged, {len(state_features)} filtered")
    return report_path, preview_path


