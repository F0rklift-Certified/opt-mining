def apply_vsicurl_env() -> None:
    """
    GDAL env for remote reads. The SRTM mosaics are .vrt indexes referencing
    .tif tiles, and NLUM is read through /vsizip/, so the allowed-extension
    list covers .tif, .vrt and .zip.
    """
    for key, value in config.VSICURL_ENV.items():
        os.environ.setdefault(key, value)


# ---------------------------------------------------------------------------
# Timestamps and banners
