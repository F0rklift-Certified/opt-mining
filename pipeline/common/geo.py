def utc_now() -> str:
    """Timestamp used across manifests and report banners."""
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def banner(module_name: str) -> str:
    """Standard do-not-edit banner for generated markdown reports."""
    return (
        f"*Generated by `pipeline.{module_name}` on {utc_now()}. "
        f"Do not edit by hand.*\n"
    )


# ---------------------------------------------------------------------------
# Atomic file writes
# ---------------------------------------------------------------------------


def atomic_write_text(path: Path, text: str) -> None:
    """Write via a sibling tmp file + rename so re-runs and interrupts are safe."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    try:
        tmp.write_text(text)
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


def atomic_write_json(path: Path, obj: object) -> None:
    """Atomically write a JSON file with 2-space indentation."""
    atomic_write_text(path, json.dumps(obj, indent=2) + "\n")


