"""
Shared helpers for geographic & environmental data retrieval.

The vector sources (ABS ASGS boundaries, DCCEEW CAPAD protected areas) are
ArcGIS REST FeatureServer layers that serve GeoJSON directly (``f=geojson``),
so no geospatial vector library is needed. Rasters (SRTM elevation, ABARES
NLUM land use) are read with rasterio, windowed over /vsicurl/ or /vsizip/
so national files are never downloaded in full.

This module also contains generic utilities (atomic writes, banners,
human_bytes, sha256_file) shared across all domain subpackages.

Licence: see DATA/geographic/DATA_PROVENANCE.md
"""

from __future__ import annotations

import hashlib
import json
import os
from datetime import datetime, timezone
from pathlib import Path

import requests

from .. import config


# ---------------------------------------------------------------------------
# Generic utilities
# ---------------------------------------------------------------------------


def human_bytes(n: int) -> str:
    """
    Format a byte count for logs and provenance tables.

    Decimal (1 MB = 10**6 bytes), matching the sizes quoted in the download
    manifest and the task documents.
    """
    step = float(n)
    for unit in ("B", "KB", "MB", "GB"):
        if step < 1000 or unit == "GB":
            return f"{step:.1f} {unit}"
        step /= 1000
    return f"{step:.1f} GB"


def sha256_file(path: Path) -> str:
    """
    SHA-256 hex digest of a file, read in 1 MiB chunks so multi-megabyte
    GeoPackages never have to be loaded into memory whole. Raises
    FileNotFoundError for a missing path.
    """
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


